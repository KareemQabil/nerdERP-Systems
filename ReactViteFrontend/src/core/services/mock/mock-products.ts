/**
 * Mock API response helpers
 */
export const createMockStandardResponse = <T>(data: T): StandardResponse<T> => ({
    success: true,
    data,
    timestamp: new Date().toISOString(),
});

export const createMockPaginatedResponse = <T>(
    data: T[],
    page: number = 1,
    limit: number = 10
): PaginatedResponse<T> => ({
    success: true,
    data: {
        data: data.slice((page - 1) * limit, page * limit),
        meta: {
            page,
            limit,
            total: data.length,
            totalPages: Math.ceil(data.length / limit),
        },
    },
    timestamp: new Date().toISOString(),
});
